package rowsmith.codegen;

import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.FieldSpec;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.NameAllocator;
import com.palantir.javapoet.ParameterizedTypeName;
import com.palantir.javapoet.TypeName;
import com.palantir.javapoet.TypeSpec;
import java.sql.Connection;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import javax.lang.model.element.Modifier;
import rowsmith.internal.gen.TypeKind;
import rowsmith.internal.schema.ColumnDef;
import rowsmith.internal.schema.ForeignKey;
import rowsmith.internal.schema.PgType;
import rowsmith.internal.schema.Schema;
import rowsmith.internal.schema.TableDef;
import rowsmith.internal.sql.ColumnRules;
import rowsmith.internal.sql.Constants;

final class DbClassGenerator {

    private static final ClassName TABLE = ClassName.get("rowsmith", "Table");
    private static final ClassName COLUMN = ClassName.get("rowsmith", "Column");
    private static final ClassName PG_ENUM = ClassName.get("rowsmith", "PgEnum");
    private static final ClassName LIST = ClassName.get(List.class);

    private enum Factory {
        PLAIN("column"), ENUM("enumColumn"), LIST("listColumn"), ENUM_LIST("enumListColumn");

        final String method;

        Factory(String method) {
            this.method = method;
        }
    }

    private record ColumnType(TypeName declared, Factory factory, TypeName argument) {}

    private record EnumSpec(ClassName name, List<String> labels, String origin) {}

    private final Schema schema;
    private final Connection connection;
    private final String packageName;
    private final ClassName db;
    private final NameAllocator typeNames = new NameAllocator();
    private final Map<PgType, EnumSpec> pgEnums = new LinkedHashMap<>();
    private final List<EnumSpec> enums = new ArrayList<>();

    DbClassGenerator(Schema schema, Connection connection, String packageName, String className) {
        this.schema = schema;
        this.connection = connection;
        this.packageName = packageName;
        this.db = ClassName.get(packageName, className);
        typeNames.newName(className);
    }

    JavaFile generate() {
        List<TableDef> tables = new ArrayList<>(schema.tables());
        tables.sort(Comparator.comparing(TableDef::qualifiedName));
        Map<TableDef, ClassName> classes = new LinkedHashMap<>();
        for (TableDef t : tables) classes.put(t, db.nestedClass(typeNames.newName(JavaNames.type(t.displayName()))));

        TypeSpec.Builder dbClass = TypeSpec.classBuilder(db)
                .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
                .addJavadoc("Tables, columns and value enums of the database, for Rowsmith. Generated from the schema; do not edit.\n")
                .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());
        NameAllocator constants = new NameAllocator();
        List<TypeSpec> tableClasses = new ArrayList<>();
        for (TableDef t : tables) {
            ClassName cls = classes.get(t);
            dbClass.addField(FieldSpec.builder(cls, constants.newName(JavaNames.constant(t.displayName())),
                    Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL).initializer("new $T()", cls).build());
            tableClasses.add(tableClass(t, cls));
        }
        dbClass.addTypes(tableClasses);
        enums.sort(Comparator.comparing(e -> e.name().simpleName()));
        for (EnumSpec e : enums) dbClass.addType(enumType(e));
        return JavaFile.builder(packageName, dbClass.build())
                .addFileComment("Generated by Rowsmith from the database schema. Do not edit.")
                .skipJavaLangImports(true)
                .indent("    ")
                .build();
    }

    private TypeSpec tableClass(TableDef t, ClassName cls) {
        TypeSpec.Builder b = TypeSpec.classBuilder(cls)
                .addModifiers(Modifier.PUBLIC, Modifier.STATIC, Modifier.FINAL)
                .superclass(TABLE)
                .addJavadoc("Table {@code $L}.\n", t.qualifiedName());
        Map<String, ColumnRules> rules = ColumnRules.ofTable(t, Constants.read(connection, ColumnRules.operands(t)));
        NameAllocator names = new NameAllocator();
        for (ColumnDef c : t.columns()) {
            ColumnType type = columnType(t, cls, c, rules.get(c.name));
            String init = type.factory().method + "($S, $T.class)";
            b.addField(FieldSpec.builder(ParameterizedTypeName.get(COLUMN, type.declared()), names.newName(JavaNames.constant(c.name)),
                            Modifier.PUBLIC, Modifier.FINAL)
                    .addJavadoc("{@code $L}\n", describe(t, c))
                    .initializer(init, c.name, type.argument())
                    .build());
        }
        b.addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE)
                .addStatement("super($S, $S)", t.schema, t.name).build());
        return b.build();
    }

    private static String describe(TableDef t, ColumnDef c) {
        StringBuilder sb = new StringBuilder(c.formattedType);
        if (c.required()) sb.append(" NOT NULL");
        if (c.isIdentity()) sb.append(" IDENTITY");
        if (c.isGenerated()) sb.append(" GENERATED (read only)");
        for (ForeignKey fk : t.foreignKeys) {
            if (fk.columns.size() == 1 && fk.columns.get(0) == c) {
                sb.append(" REFERENCES ").append(fk.refTable().qualifiedName()).append('(').append(fk.refColumns().get(0).name).append(')');
            }
        }
        return sb.toString();
    }

    private ColumnType columnType(TableDef t, ClassName tableClass, ColumnDef c, ColumnRules rules) {
        PgType type = TypeKind.strip(c.type);
        return switch (TypeKind.of(type)) {
            case ENUM -> {
                ClassName e = pgEnum(type);
                yield new ColumnType(e, Factory.ENUM, e);
            }
            case ARRAY -> {
                PgType element = TypeKind.strip(type.element());
                if (TypeKind.of(element) == TypeKind.ENUM) {
                    ClassName e = pgEnum(element);
                    yield new ColumnType(ParameterizedTypeName.get(LIST, e), Factory.ENUM_LIST, e);
                }
                TypeName e = TypeName.get(TypeKind.of(element).javaType());
                yield new ColumnType(ParameterizedTypeName.get(LIST, e), Factory.LIST, e);
            }
            case TEXT -> {
                List<String> labels = checkLabels(rules);
                if (labels == null) yield new ColumnType(ClassName.get(String.class), Factory.PLAIN, ClassName.get(String.class));
                ClassName e = db.nestedClass(typeNames.newName(tableClass.simpleName() + JavaNames.type(c.name)));
                enums.add(new EnumSpec(e, labels, "Values allowed by CHECK " + rules.allowedSource + " on {@code "
                        + t.qualifiedName() + "." + c.name + "}."));
                yield new ColumnType(e, Factory.ENUM, e);
            }
            default -> {
                TypeName s = TypeName.get(TypeKind.of(type).javaType());
                yield new ColumnType(s, Factory.PLAIN, s);
            }
        };
    }

    private static List<String> checkLabels(ColumnRules rules) {
        if (rules == null || rules.allowed == null || rules.allowed.isEmpty()) return null;
        LinkedHashSet<String> labels = new LinkedHashSet<>();
        for (Object v : rules.allowed) {
            if (!(v instanceof String s)) return null;
            labels.add(s);
        }
        return new ArrayList<>(labels);
    }

    private ClassName pgEnum(PgType type) {
        return pgEnums.computeIfAbsent(type, t -> {
            EnumSpec e = new EnumSpec(db.nestedClass(typeNames.newName(JavaNames.type(t.castName))), t.enumLabels,
                    "Labels of the Postgres enum {@code " + t.schema + "." + t.name + "}.");
            enums.add(e);
            return e;
        }).name();
    }

    private static TypeSpec enumType(EnumSpec e) {
        NameAllocator names = new NameAllocator();
        TypeSpec.Builder b = TypeSpec.enumBuilder(e.name())
                .addModifiers(Modifier.PUBLIC)
                .addSuperinterface(PG_ENUM)
                .addJavadoc("$L\n", e.origin());
        for (String label : e.labels()) {
            b.addEnumConstant(names.newName(JavaNames.constant(label)), TypeSpec.anonymousClassBuilder("$S", label).build());
        }
        return b.addField(String.class, "label", Modifier.PRIVATE, Modifier.FINAL)
                .addMethod(MethodSpec.constructorBuilder()
                        .addParameter(String.class, "label")
                        .addStatement("this.label = label").build())
                .addMethod(MethodSpec.methodBuilder("label")
                        .addAnnotation(Override.class)
                        .addModifiers(Modifier.PUBLIC)
                        .returns(String.class)
                        .addStatement("return label").build())
                .build();
    }
}
