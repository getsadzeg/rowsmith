package io.github.rowsmith;

import io.github.rowsmith.internal.config.RowsmithClock;
import io.github.rowsmith.internal.plan.Engine;
import io.github.rowsmith.internal.util.CallSite;
import java.time.Clock;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Consumer;
import javax.sql.DataSource;

/**
 * Creates valid, connected Postgres rows with predictable values. Describe only what matters; Rowsmith creates the rest.
 *
 * <pre>{@code
 * Rowsmith rowsmith = Rowsmith.of(dataSource);           // reads the catalog once
 * Row project = rowsmith.create(PROJECT, p -> p
 *     .with(TASK, 2, TaskData::overdue)                  // TASK, PROJECT: generated by rowsmith-codegen
 *     .with(TASK, t -> t.set(TASK.STATUS, TaskStatus.DONE)));
 * long id = project.getLong("id");
 * }</pre>
 *
 * Every method also accepts table and column names as strings.
 *
 * Not thread-safe: use one instance per test (the JUnit extension does this for you).
 */
public final class Rowsmith {

    private final Engine engine;

    private Rowsmith(Engine engine) {
        this.engine = engine;
    }

    /** A Rowsmith for this DataSource with the system clock. */
    public static Rowsmith of(DataSource dataSource) {
        return builder(dataSource).build();
    }

    public static Builder builder(DataSource dataSource) {
        return new Builder(dataSource);
    }

    public static final class Builder {
        private final DataSource dataSource;
        private Clock clock = Clock.systemDefaultZone();

        private Builder(DataSource dataSource) {
            if (dataSource == null) throw new RowsmithException(ErrorCode.NO_DATASOURCE, "DataSource must not be null");
            this.dataSource = dataSource;
        }

        /** The clock for "today"/"now" (default: the system clock); use the application's clock, or a fixed one in tests. */
        public Builder clock(Clock clock) { this.clock = clock; return this; }

        public Rowsmith build() {
            return new Rowsmith(new Engine(dataSource, new RowsmithClock(clock), List.of(), new InternalAccess()));
        }
    }

    public Row create(String table) {
        return create(table, s -> {});
    }

    public Row create(String table, Consumer<RowSpec> spec) {
        return run(List.of(RowSpec.of(table, spec))).get(0);
    }

    /** Creates {@code count} rows of a table in one call; they share auto-created parents. */
    public List<Row> createMany(String table, int count) {
        return createMany(table, count, s -> {});
    }

    public List<Row> createMany(String table, int count, Consumer<RowSpec> spec) {
        List<RowSpec> specs = specs(table, count, spec);
        return count == 0 ? List.of() : run(specs);
    }

    /** Creates one row of a generated table constant, e.g. {@code create(TASK, t -> t.set(TASK.STATUS, DONE))}. */
    public Row create(Table table) {
        return create(table.qualifiedName());
    }

    public Row create(Table table, Consumer<RowSpec> spec) {
        return create(table.qualifiedName(), spec);
    }

    public List<Row> createMany(Table table, int count) {
        return createMany(table.qualifiedName(), count);
    }

    public List<Row> createMany(Table table, int count, Consumer<RowSpec> spec) {
        return createMany(table.qualifiedName(), count, spec);
    }

    public Plan plan(Table table) {
        return plan(table.qualifiedName());
    }

    public Plan plan(Table table, Consumer<RowSpec> spec) {
        return plan(table.qualifiedName(), spec);
    }

    public Plan planMany(Table table, int count, Consumer<RowSpec> spec) {
        return planMany(table.qualifiedName(), count, spec);
    }

    /** Plans without inserting anything: the rows and SQL that create(...) would produce. */
    public Plan plan(String table) {
        return plan(table, s -> {});
    }

    public Plan plan(String table, Consumer<RowSpec> spec) {
        return plan(List.of(RowSpec.of(table, spec)));
    }

    public Plan planMany(String table, int count, Consumer<RowSpec> spec) {
        return plan(specs(table, count, spec));
    }

    private static List<RowSpec> specs(String table, int count, Consumer<RowSpec> spec) {
        if (count < 0) throw new IllegalArgumentException("count must be >= 0, was " + count);
        List<RowSpec> specs = new ArrayList<>();
        for (int i = 0; i < count; i++) specs.add(RowSpec.of(table, spec));
        return specs;
    }

    private static RowsmithException withSite(RowsmithException e, String site) {
        if (site.isEmpty()) return e;
        RowsmithException r = new RowsmithException(e.code(), e.detail() + " " + site, e.getCause());
        r.setStackTrace(e.getStackTrace());
        return r;
    }

    private Plan plan(List<RowSpec> specs) {
        String site = CallSite.find();
        try {
            Engine.Planned p = engine.plan(specs);
            return new Plan(p.rows(), p.sql());
        } catch (RowsmithException e) {
            throw withSite(e, site);
        }
    }

    private List<Row> run(List<RowSpec> specs) {
        String site = CallSite.find();
        try {
            return engine.create(specs);
        } catch (RowsmithException e) {
            throw withSite(e, site);
        }
    }

    /** Loads an existing row by primary key, e.g. to pass it to {@link RowSpec#use(Row)}. */
    public Row find(String table, Object id) {
        return engine.find(table, id);
    }

    /** Loads an existing row by primary key. */
    public Row find(Table table, Object id) {
        return find(table.qualifiedName(), id);
    }
}
