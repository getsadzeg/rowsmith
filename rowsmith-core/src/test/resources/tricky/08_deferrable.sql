-- A required FK cycle that is breakable because one side is DEFERRABLE INITIALLY DEFERRED.
CREATE TABLE team (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  captain_id bigint NOT NULL
);
CREATE TABLE player (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  team_id bigint NOT NULL REFERENCES team(id)
);
ALTER TABLE team ADD CONSTRAINT team_captain_fk FOREIGN KEY (captain_id) REFERENCES player(id) DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE audit_note (
  id serial PRIMARY KEY,
  team_id bigint NOT NULL REFERENCES team(id) DEFERRABLE INITIALLY IMMEDIATE,
  note text NOT NULL
);
