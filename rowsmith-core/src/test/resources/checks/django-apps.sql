-- case: netbox/users_token.enforce_version_dependent_fields
-- source: https://github.com/netbox-community/netbox/blob/ddcb3ce2d2ae4c413baf5f6a0f46855eac91049e/netbox/users/models/tokens.py
-- license: Apache-2.0
-- expect: CLEAR_ERROR
CREATE TABLE users_token (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version smallint NOT NULL CHECK ("version" >= 0),
  description varchar(200) NOT NULL,
  created timestamp with time zone NOT NULL,
  expires timestamp with time zone,
  enabled boolean NOT NULL,
  write_enabled boolean NOT NULL,
  plaintext varchar(40),
  key varchar(12),
  pepper_id smallint CHECK ("pepper_id" >= 0),
  hmac_digest varchar(64),
  CONSTRAINT enforce_version_dependent_fields CHECK (
    ("hmac_digest" IS NULL AND "key" IS NULL AND "pepper_id" IS NULL AND "plaintext" IS NOT NULL AND "version" = 1)
    OR ("hmac_digest" IS NOT NULL AND "key" IS NOT NULL AND "pepper_id" IS NOT NULL AND "plaintext" IS NULL AND "version" = 2)));

